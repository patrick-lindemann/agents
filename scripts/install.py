#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

_HARNESSES = ("claude", "codex", "pi")
_REPO_DIR = Path(__file__).resolve().parent.parent
_DIST_DIR = _REPO_DIR / "dist"
_HOME_DIR = Path.home()
_CONFIG_DIRS = {
    "claude": Path(os.environ.get("CLAUDE_CONFIG_DIR") or _HOME_DIR / ".claude"),
    "codex": Path(os.environ.get("CODEX_HOME") or _HOME_DIR / ".codex"),
    "pi": Path(os.environ.get("PI_CODING_AGENT_DIR") or _HOME_DIR / ".pi" / "agent"),
}
# Optional and git-ignored: {"<harness>": {"<tier>": "<model>"}}. A tier without an entry
# runs on the session's model.
_MODELS_FILE = _REPO_DIR / "models.local.json"

# The neutral tool groups of a role, per harness. `all` omits the tool list.
_CLAUDE_TOOLS = {
    "read": ("Read",),
    "search": ("Grep", "Glob"),
    "commands": ("Bash",),
    "web": ("WebFetch", "WebSearch"),
    "edit": ("Edit", "Write"),
}
_PI_TOOLS = {
    "read": ("read",),
    "search": ("grep", "find", "ls"),
    "commands": ("bash",),
    "web": ("web_search", "fetch_content", "get_search_content"),
    "edit": ("edit", "write"),
}
# Loaded into Pi subagents, which load no extensions of their own in the foreground, so
# that they get the rules too. The path is the one this script links, so that a
# background child, which also discovers it there, loads it once.
_PI_RULES_EXTENSION_FILE = _CONFIG_DIRS["pi"] / "extensions" / "agents-rules" / "index.ts"

_CODEX_HOOK_COMMAND = 'python3 "$HOME/agents/adapters/codex/hooks/rules_hook.py"'
# Generated files start with a marker, so that only they are replaced or removed. They
# are recognized by its prefix, so that other wording after it still counts.
_ROLE_COPY_MARKER = "# Generated from ~/agents/roles by scripts/install.py, edit there."
_ROLE_COPY_PREFIX = "# Generated from ~/agents/roles"
_GIT_HOOK_MARKER = "# Generated by scripts/install.py, runs it after every pull."
_GIT_HOOK_PREFIX = "# Generated by scripts/install."
_BLOCK_NAME = "agents-rules"


class Arguments(argparse.Namespace):
    harnesses: list[str] | None


@dataclass(frozen=True)
class _Role:
    name: str
    description: str
    tier: str
    effort: str
    tools: tuple[str, ...]
    body: str
    file_name: str


def get_args() -> Arguments:
    """Parse the command-line arguments.

    Returns:
        The parsed arguments.
    """
    parser = argparse.ArgumentParser(
        description=("Install the skills, subagent roles and rules of this repository for Claude Code, Codex and Pi.")
    )
    parser.add_argument(
        "--harness",
        dest="harnesses",
        type=_parse_harnesses,
        help="comma-separated harnesses to install for, by default every installed one",
    )
    return parser.parse_args(namespace=Arguments())


def main() -> None:
    """Install for each selected harness that is installed on this machine."""
    args = get_args()
    selected = _select_installed(args.harnesses or _HARNESSES)
    _install_git_hooks(args.harnesses)
    # A fixed path for the skills and rules, which refer to ~/agents/... wherever the
    # checkout is.
    if _REPO_DIR != _HOME_DIR / "agents":
        _link(_REPO_DIR, _HOME_DIR / "agents")

    print(f"harnesses: {' '.join(selected) or 'none'}")
    if selected:
        _build_roles(_DIST_DIR, selected)
    _build_skills()

    claude_dir, codex_dir, pi_dir = (_CONFIG_DIRS[harness] for harness in _HARNESSES)
    # Claude Code and the Pi extension read the rules from ~/.claude/rules. The Codex hook
    # reads ~/agents/rules.
    if "claude" in selected or "pi" in selected:
        rules_dir = claude_dir / "rules"
        rules_dir.mkdir(parents=True, exist_ok=True)
        _link(_REPO_DIR / "rules", rules_dir / "agents")
        _prune(rules_dir)
    if "claude" in selected:
        _link_skills(claude_dir / "skills")
        _link_roles("claude", claude_dir / "agents")
    # The Agent Skills location, which Codex and Pi read.
    _link_skills(_HOME_DIR / ".agents" / "skills")
    if "codex" in selected:
        _copy_codex_roles(codex_dir / "agents")
        _remove_block(codex_dir / "AGENTS.md", _BLOCK_NAME)
        if _add_codex_hooks(codex_dir / "hooks.json"):
            print("codex: run /hooks once to trust the new rules hooks")
    if "pi" in selected:
        _link_roles("pi", pi_dir / "agents")
        _remove_block(pi_dir / "AGENTS.md", _BLOCK_NAME)
        extensions_dir = pi_dir / "extensions"
        extensions_dir.mkdir(parents=True, exist_ok=True)
        _link(_REPO_DIR / "adapters" / "pi" / "extensions" / "rules", extensions_dir / "agents-rules")


def _parse_harnesses(text: str) -> list[str]:
    harnesses = [harness for harness in re.split(r"[,\s]+", text) if harness]
    for harness in harnesses:
        if harness not in _HARNESSES:
            raise argparse.ArgumentTypeError(f"unknown harness {harness!r}, known are {', '.join(_HARNESSES)}")
    return harnesses


def _select_installed(harnesses: Sequence[str]) -> list[str]:
    selected = []
    for harness in harnesses:
        config_dir = _CONFIG_DIRS[harness]
        if shutil.which(harness) or config_dir.is_dir():
            selected.append(harness)
        else:
            print(f"skip {harness}: not installed (no `{harness}` on PATH, no {config_dir})", file=sys.stderr)
    return selected


def _install_git_hooks(harnesses: Sequence[str] | None) -> None:
    if not (_REPO_DIR / ".git").exists():
        return
    result = subprocess.run(
        ["git", "-C", str(_REPO_DIR), "rev-parse", "--path-format=absolute", "--git-path", "hooks"],
        check=True,
        capture_output=True,
        text=True,
    )
    hooks_dir = Path(result.stdout.strip())
    arguments = ["--harness", ",".join(harnesses)] if harnesses else []
    # A pull that merges or fast-forwards runs post-merge, also with --rebase. A rebase pull
    # that replays local commits runs only post-rewrite, which `commit --amend` runs too.
    _write_git_hook(hooks_dir / "post-merge", "", arguments)
    _write_git_hook(hooks_dir / "post-rewrite", 'if sys.argv[1:2] != ["rebase"]:\n    sys.exit(0)\n', arguments)


def _write_git_hook(hook_file: Path, guard: str, arguments: Sequence[str]) -> None:
    if hook_file.exists() and not _read_line(hook_file, 1).startswith(_GIT_HOOK_PREFIX):
        print(f"skip {hook_file}: exists and was not made by install.py", file=sys.stderr)
        return
    command = [str(_REPO_DIR / "scripts" / "install.py"), *arguments]
    text = (
        "#!/usr/bin/env python3\n"
        f"{_GIT_HOOK_MARKER}\n"
        "import os\n"
        "import sys\n"
        "\n"
        f"{guard}"
        f"os.execv(sys.executable, [sys.executable, *{command!r}])\n"
    )
    if hook_file.exists() and hook_file.read_text(encoding="utf-8", errors="replace") == text:
        return
    hook_file.parent.mkdir(parents=True, exist_ok=True)
    hook_file.write_text(text, encoding="utf-8")
    hook_file.chmod(0o755)
    print(f"write {hook_file}")


def _link(source: Path, target: Path) -> None:
    """Link `target` to `source`, replacing only an existing symlink, never a real file."""
    if target.exists() and not target.is_symlink():
        print(f"skip {target}: exists and is not a symlink", file=sys.stderr)
        return
    if target.is_symlink():
        if os.readlink(target) == str(source):
            return
        target.unlink()
    target.symlink_to(source)
    print(f"link {target} -> {source}")


def _prune(directory: Path) -> None:
    """Remove the links in `directory` that point into this repository but no longer resolve."""
    for entry in sorted(directory.iterdir()):
        if entry.is_symlink() and os.readlink(entry).startswith(f"{_REPO_DIR}/") and not entry.exists():
            entry.unlink()
            print(f"remove {entry}")


def _link_skills(target_dir: Path) -> None:
    target_dir.mkdir(parents=True, exist_ok=True)
    for skill_dir in sorted(path for path in (_REPO_DIR / "skills").iterdir() if path.is_dir()):
        _link(skill_dir, target_dir / skill_dir.name)
    _prune(target_dir)


def _link_roles(harness: str, target_dir: Path) -> None:
    target_dir.mkdir(parents=True, exist_ok=True)
    for role_file in sorted((_DIST_DIR / harness / "agents").iterdir()):
        _link(role_file, target_dir / role_file.name)
    _prune(target_dir)


def _copy_codex_roles(target_dir: Path) -> None:
    """Copy the generated Codex roles into `target_dir`.

    Codex lists a linked agent file but cannot spawn it ("agent type is currently not
    available", 0.167.2), so the files are copies.
    """
    source_dir = _DIST_DIR / "codex" / "agents"
    target_dir.mkdir(parents=True, exist_ok=True)
    for target in sorted(target_dir.glob("*.toml")):
        if target.is_symlink():
            if os.readlink(target).startswith(f"{_REPO_DIR}/"):
                target.unlink()
        elif (
            target.is_file()
            and _read_line(target, 0).startswith(_ROLE_COPY_PREFIX)
            and not (source_dir / target.name).exists()
        ):
            target.unlink()
            print(f"remove {target}")
    for role_file in sorted(source_dir.glob("*.toml")):
        target = target_dir / role_file.name
        if target.exists() and not _read_line(target, 0).startswith(_ROLE_COPY_PREFIX):
            print(f"skip {target}: exists and was not made by install.py", file=sys.stderr)
            continue
        text = f"{_ROLE_COPY_MARKER}\n{role_file.read_text(encoding='utf-8')}"
        if target.exists() and target.read_text(encoding="utf-8") == text:
            continue
        target.write_text(text, encoding="utf-8")
        print(f"copy {target}")


def _add_codex_hooks(hooks_file: Path) -> bool:
    """Add the rules hooks to a Codex `hooks.json`, once each, and leave every other hook alone.

    Returns:
        Whether the file changed.
    """
    wanted = (
        ("SessionStart", "startup|clear|compact", "session-start"),
        ("SubagentStart", None, "session-start"),
        ("PreToolUse", "^(apply_patch|Bash)$", "pre-tool-use"),
    )
    try:
        config = json.loads(hooks_file.read_text(encoding="utf-8"))
    except FileNotFoundError:
        config = {}
    hooks = config.setdefault("hooks", {})
    is_changed = False
    for event, matcher, mode in wanted:
        groups = hooks.setdefault(event, [])
        # The rules of one language are about 6,000 tokens. Codex shortens context above the
        # limit, by default 2,500 tokens.
        entry = {
            "type": "command",
            "command": f"{_CODEX_HOOK_COMMAND} {mode}",
            "timeout": 10,
            "additionalContextLimit": 12000,
        }
        group = ({"matcher": matcher} if matcher else {}) | {"hooks": [entry]}
        index = next(
            (index for index, existing in enumerate(groups) if _is_rules_hook_group(existing, mode)),
            None,
        )
        if index is not None and groups[index] == group:
            continue
        if index is None:
            groups.append(group)
        else:
            groups[index] = group
        is_changed = True
        print(f"{'add' if index is None else 'update'} {event} hook in {hooks_file}")
    if is_changed:
        hooks_file.write_text(f"{json.dumps(config, indent=2, ensure_ascii=False)}\n", encoding="utf-8")
    return is_changed


def _is_rules_hook_group(group: Mapping[str, object], mode: str) -> bool:
    """Tell whether `group` runs a rules hook of this repository in `mode`.

    Matched by directory and argument rather than the full command, so that a hook
    registered from another path to this repository or with another interpreter is
    replaced, not duplicated.
    """
    hooks = group.get("hooks")
    if not isinstance(hooks, list):
        return False
    return any(
        isinstance(hook, dict)
        and isinstance(command := hook.get("command"), str)
        and "/adapters/codex/hooks/" in command
        and command.endswith(f" {mode}")
        for hook in hooks
    )


def _remove_block(file_path: Path, name: str) -> None:
    """Remove the generated block `name` from `file_path`, if there is one."""
    if not file_path.exists():
        return
    begin = f"<!-- BEGIN {name}: generated by ~/agents/scripts, do not edit -->"
    end = f"<!-- END {name} -->"
    text = file_path.read_text(encoding="utf-8")
    updated = re.sub(rf"\n*{re.escape(begin)}.*?{re.escape(end)}\n?", "\n", text, flags=re.DOTALL).strip("\n")
    updated = f"{updated}\n" if updated else ""
    if updated != text:
        file_path.write_text(updated, encoding="utf-8")
        print(f"remove block {name} from {file_path}")


def _build_roles(outdir: Path, harnesses: Sequence[str]) -> None:
    """Write `<outdir>/<harness>/agents/` from `roles/` for each of `harnesses`."""
    models = json.loads(_MODELS_FILE.read_text(encoding="utf-8")) if _MODELS_FILE.exists() else {}
    roles = _load_roles()
    for harness in _HARNESSES:
        if harness not in harnesses:
            continue
        agents_dir = outdir / harness / "agents"
        agents_dir.mkdir(parents=True, exist_ok=True)
        for stale_file in agents_dir.iterdir():
            stale_file.unlink()
        for role in roles:
            model = models.get(harness, {}).get(role.tier) or None
            match harness:
                case "claude":
                    text, suffix = _render_claude_role(role, model), ".md"
                case "codex":
                    text, suffix = _render_codex_role(role, model), ".toml"
                case "pi":
                    text, suffix = _render_pi_role(role, model), ".md"
                case _:
                    raise ValueError(f"Unknown harness {harness!r}.")
            (agents_dir / f"{role.name}{suffix}").write_text(text, encoding="utf-8")


def _load_roles() -> list[_Role]:
    roles = []
    for role_file in sorted((_REPO_DIR / "roles").glob("*.md")):
        fields, body = _split_front_matter(role_file.read_text(encoding="utf-8"))
        tools = _require_field(fields, "tools", role_file).split(",")
        roles.append(
            _Role(
                name=_require_field(fields, "name", role_file),
                description=_require_field(fields, "description", role_file),
                tier=_require_field(fields, "tier", role_file),
                effort=_require_field(fields, "effort", role_file),
                tools=tuple(tool.strip() for tool in tools),
                body=body.lstrip("\n"),
                file_name=role_file.name,
            )
        )
    return roles


def _require_field(fields: Mapping[str, str | list[str]], key: str, file_path: Path) -> str:
    value = fields.get(key)
    if not isinstance(value, str) or not value:
        raise ValueError(f"Cannot build the role `{file_path}`: its frontmatter has no `{key}`.")
    return value


def _render_claude_role(role: _Role, model: str | None) -> str:
    lines = ["---", f"name: {role.name}", f"description: {_quote(role.description)}"]
    if not _has_all_tools(role):
        lines.append(f"tools: {', '.join(tool for group in role.tools for tool in _CLAUDE_TOOLS[group])}")
    lines += [f"model: {model or 'inherit'}", f"effort: {role.effort}", "---", "", role.body]
    return "\n".join(lines)


def _render_pi_role(role: _Role, model: str | None) -> str:
    lines = ["---", f"name: {role.name}", f"description: {_quote(role.description)}"]
    if not _has_all_tools(role):
        groups = list(role.tools)
        if "web" in groups and not _has_pi_web_tools():
            print(f"pi: {role.name}: pi-web-access is not installed, so no web tools", file=sys.stderr)
            groups = [group for group in groups if group != "web"]
        # Only a background child loads the installed extensions, pi-web-access among them.
        if "web" in groups:
            lines.append("async: true")
        lines.append(f"tools: {', '.join(tool for group in groups for tool in _PI_TOOLS[group])}")
    if model:
        lines.append(f"model: {model}")
    lines += [
        f"subagentOnlyExtensions: {_PI_RULES_EXTENSION_FILE}",
        f"thinking: {role.effort}",
        "inheritProjectContext: true",
        "inheritSkills: false",
        "---",
        "",
        role.body,
    ]
    return "\n".join(lines)


def _render_codex_role(role: _Role, model: str | None) -> str:
    body = role.body
    if "'''" in body:
        raise ValueError(f"Cannot build the role `{role.file_name}`: ''' cannot go into a TOML literal string.")
    # Codex has no per-agent tool list. The sandbox is the parent's.
    if "edit" not in role.tools and not _has_all_tools(role):
        body = f"Change no file.\n\n{body}"
    lines = [f"name = {_quote(role.name)}", f"description = {_quote(role.description)}"]
    if model:
        lines.append(f"model = {_quote(model)}")
    lines += [f"model_reasoning_effort = {_quote(role.effort)}", f"developer_instructions = '''\n{body}'''", ""]
    return "\n".join(lines)


def _has_all_tools(role: _Role) -> bool:
    return role.tools == ("all",)


def _has_pi_web_tools() -> bool:
    try:
        settings = json.loads((_CONFIG_DIRS["pi"] / "settings.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    return any("pi-web-access" in json.dumps(package) for package in settings.get("packages", []))


def _build_skills() -> None:
    """Write `agents/openai.yaml` for each user-invoked skill and remove it from the others.

    Codex reads the name, description and `metadata.short-description` from `SKILL.md`
    itself, so only a user-invoked skill needs the file, for its policy.
    """
    text = "policy:\n  allow_implicit_invocation: false\n"
    for skill_dir in sorted((_REPO_DIR / "skills").iterdir()):
        skill_file = skill_dir / "SKILL.md"
        if not skill_file.exists():
            continue
        fields, _ = _split_front_matter(skill_file.read_text(encoding="utf-8"))
        agents_dir = skill_dir / "agents"
        policy_file = agents_dir / "openai.yaml"
        if fields.get("disable-model-invocation") != "true":
            if policy_file.exists():
                policy_file.unlink()
                if not any(agents_dir.iterdir()):
                    agents_dir.rmdir()
                print(f"remove {policy_file}")
            continue
        if policy_file.exists() and policy_file.read_text(encoding="utf-8") == text:
            continue
        agents_dir.mkdir(parents=True, exist_ok=True)
        policy_file.write_text(text, encoding="utf-8")
        print(f"write {policy_file}")


def _split_front_matter(text: str) -> tuple[dict[str, str | list[str]], str]:
    """Split the flat frontmatter of a role or skill from its body.

    It reads `key: value` lines, quoted values as JSON, and `  - item` lists. Nested keys,
    such as those under `metadata:`, are read as top-level keys.
    """
    match = re.fullmatch(r"---\n(.*?)\n---\n(.*)", text, flags=re.DOTALL)
    if match is None:
        return {}, text
    fields: dict[str, str | list[str]] = {}
    key = ""
    for line in match.group(1).split("\n"):
        if line.startswith("  - ") and key:
            existing = fields.get(key)
            items = existing if isinstance(existing, list) else []
            items.append(line[4:].strip().strip('"'))
            fields[key] = items
        elif ":" in line:
            key, _, value = line.partition(":")
            key = key.strip()
            value = value.strip()
            if len(value) >= 2 and value.startswith('"') and value.endswith('"'):
                value = json.loads(value)
            fields[key] = value or []
    return fields, match.group(2)


def _quote(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _read_line(file_path: Path, index: int) -> str:
    lines = file_path.read_text(encoding="utf-8", errors="replace").splitlines()
    return lines[index] if index < len(lines) else ""


if __name__ == "__main__":
    main()
